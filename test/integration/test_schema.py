def test_documented_secondary_indexes_exist_by_column_coverage(live: dict[str, Any]) -> None:
    rows = _query(live["db"], "SELECT table_name, index_name, column_name FROM information_schema.statistics WHERE table_schema = %s ORDER BY table_name, index_name, seq_in_index")
    by_index: dict[tuple[str, str], list[str]] = defaultdict(list)
    for t, i, c in rows:
        by_index[(_text(t), _text(i))].append(_text(c))
    for table, columns in DOCUMENTED_INDEX_COLUMNS:
        assert list(columns) in [v for (t, _), v in by_index.items() if t == table], f"missing index on {table}{columns}"


def test_documented_index_names_exist(live: dict[str, Any]) -> None:
    documented = parse_documented_ddl(SCHEMA_MD.read_text(encoding="utf-8"))
    rows = _query(live["db"], "SELECT table_name, index_name FROM information_schema.statistics WHERE table_schema = %s")
    present = {(_text(t), _text(i)) for t, i in rows}
    for table, spec in documented.items():
        for name in spec["indexes"]:
            assert (table, name) in present, f"{table}.{name}"


@pytest.mark.parametrize("table", ["document", "task", "knowledgebase"])
def test_documented_tables_match_schema_md(live: dict[str, Any], table: str) -> None:
    documented = parse_documented_ddl(SCHEMA_MD.read_text(encoding="utf-8"))[table]["columns"]
    actual = _columns(live["db"])[table]
    for name, want in documented.items():
        assert name in actual, f"{table}.{name} missing"
        assert actual[name]["type"] == want["type"], f"{table}.{name} type {actual[name]['type']} != {want['type']}"
        assert actual[name]["nullable"] == want["nullable"], f"{table}.{name} nullability"
        assert actual[name]["default"] == want["default"], f"{table}.{name} default {actual[name]['default']!r} != {want['default']!r}"


