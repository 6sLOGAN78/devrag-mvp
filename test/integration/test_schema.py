def test_live_columns_match_committed_schema_json(live: dict[str, Any]) -> None:
    exported = {t["name"]: t for t in json.loads(SCHEMA_JSON.read_text(encoding="utf-8"))["tables"]}
    actual = _columns(live["db"])
    assert set(actual) == set(exported)
    for table, spec in exported.items():
        assert set(actual[table]) == {c["name"] for c in spec["columns"]}, table
        for col in spec["columns"]:
            got = actual[table][col["name"]]
            assert got["type"] == col["type"], f"{table}.{col['name']} type"
            assert got["nullable"] == col["nullable"], f"{table}.{col['name']} nullable"
            assert got["default"] == col["default"], f"{table}.{col['name']} default"


def test_live_indexes_match_committed_schema_json(live: dict[str, Any]) -> None:
    rows = _query(live["db"], "SELECT table_name, index_name, column_name FROM information_schema.statistics WHERE table_schema = %s ORDER BY table_name, index_name, seq_in_index")
    actual: dict[tuple[str, str], list[str]] = defaultdict(list)
    for t, i, c in rows:
        actual[(_text(t), _text(i))].append(_text(c))
    for table in json.loads(SCHEMA_JSON.read_text(encoding="utf-8"))["tables"]:
        for index in table["indexes"]:
            assert actual.get((table["name"], index["name"])) == index["columns"], f"{table['name']}.{index['name']}"


def test_extra_migration_in_temp_dir_applies_once(tmp_path: Path) -> None:
    for source in DEFAULT_MIGRATIONS_DIR.glob("000[12]_*.py"):
        shutil.copy(source, tmp_path / source.name)
    (tmp_path / "0003_marker.py").write_text(
        'VERSION = "0003"\n\ndef upgrade(db):\n    db.execute_sql("CREATE TABLE IF NOT EXISTS marker_three (id INT PRIMARY KEY)")\n',
        encoding="utf-8",
    )
    with scratch_database() as name:
        database = init_database(app_connection_settings(name))
        try:
            assert run_migrations(migrations_dir=tmp_path) == ["0001", "0002", "0003"]
            assert run_migrations(migrations_dir=tmp_path) == []
            with DB.connection_context():
                assert current_version() == 3
        finally:
            database.close_all()
            DB.initialize(None)


def test_rerun_after_partial_baseline_adds_missing_index_and_tables() -> None:
    """R-75: an interrupted 0002 (one table dropped, one index dropped) is repaired by a rerun."""
    with scratch_database() as name:
        database = init_database(app_connection_settings(name))
        try:
            run_migrations()
            with DB.connection_context():
                DB.execute_sql("DROP TABLE `memory`")
                DB.execute_sql("ALTER TABLE `document` DROP INDEX `idx_doc_kb_id`")
                DB.execute_sql("UPDATE system_settings SET value = '0001' WHERE name = 'schema.version'")
            assert run_migrations() == ["0002"]
            tables = {_text(r[0]) for r in _query(name, "SELECT table_name FROM information_schema.tables WHERE table_schema = %s")}
            assert "memory" in tables
            names = {_text(r[0]) for r in _query(name, "SELECT index_name FROM information_schema.statistics WHERE table_schema = %s AND table_name = 'document'")}
            assert any(n for n in names if n != "PRIMARY") and "idx_doc_kb_id" not in names
            cols = _query(name, "SELECT column_name FROM information_schema.statistics WHERE table_schema = %s AND table_name = 'document' AND index_name <> 'PRIMARY'")
            assert "kb_id" in {_text(c[0]) for c in cols}
        finally:
            database.close_all()
            DB.initialize(None)
