def _query(db_name: str, sql: str) -> list[tuple[Any, ...]]:
    with DB.connection_context():
        return [tuple(r) for r in DB.execute_sql(sql, (db_name,)).fetchall()]


def _text(value: Any) -> Any:
    return value.decode() if isinstance(value, bytes) else value


def _columns(db_name: str, table: str | None = None) -> dict[str, dict[str, dict[str, Any]]]:
    rows = _query(db_name, "SELECT table_name, column_name, column_type, is_nullable, column_default FROM information_schema.columns WHERE table_schema = %s")
    out: dict[str, dict[str, dict[str, Any]]] = defaultdict(dict)
    for t, c, ctype, nullable, default in rows:
        out[_text(t)][_text(c)] = {"type": _text(ctype), "nullable": _text(nullable) == "YES", "default": _text(default)}
    return out


def parse_documented_ddl(markdown: str) -> dict[str, dict[str, Any]]:
    """Parse the CREATE TABLE statements in schema.md into columns and index definitions."""
    tables: dict[str, dict[str, Any]] = {}
    for block in re.findall(r"```sql\n(.*?)```", markdown, re.S):
        match = re.search(r"CREATE TABLE `(\w+)` \((.*)\);", block, re.S)
        if not match:
            continue
        columns: dict[str, dict[str, Any]] = {}
        indexes: dict[str, tuple[str, ...]] = {}
        for raw in match.group(2).splitlines():
            line = raw.strip().rstrip(",")
            if not line:
                continue
            idx = re.match(r"INDEX `(\w+)` \(`(\w+)`\)$", line)
            if idx:
                indexes[idx.group(1)] = (idx.group(2),)
                continue
            col = re.match(r"`(\w+)` (\w+(?:\(\d+\))?)(.*)$", line)
            assert col, f"unparsed DDL line: {line}"
            rest = col.group(3)
            default = re.search(r"DEFAULT ('([^']*)'|\S+)", rest)
            primary = "PRIMARY KEY" in rest
            columns[col.group(1)] = {
                "type": col.group(2),
                "nullable": "NOT NULL" not in rest and not primary,
                "default": None if not default else (default.group(2) if default.group(2) is not None else default.group(1)),
            }
        tables[match.group(1)] = {"columns": columns, "indexes": indexes}
    return tables


def test_documented_ddl_parser_finds_the_three_tables() -> None:
    parsed = parse_documented_ddl(SCHEMA_MD.read_text(encoding="utf-8"))
    assert set(parsed) == {"document", "task", "knowledgebase"}
    assert parsed["document"]["columns"]["kb_id"] == {"type": "varchar(256)", "nullable": False, "default": None}
    assert parsed["document"]["columns"]["run"] == {"type": "varchar(1)", "nullable": True, "default": "0"}


